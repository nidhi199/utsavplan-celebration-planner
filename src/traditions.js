export const ALLOWED_TRADITION_IDS = TRADITIONS.map(t => t.id);
export const TRADITION_MAP = Object.fromEntries(TRADITIONS.map(t => [t.id, t]));

/**
 * Returns a tradition object by its id.
 * @param {string} id
 * @returns {object|null}
 */
export function getTradition(id) {
  if (!id || typeof id !== 'string') return null;
  const cleanId = id.trim().toLowerCase();
  return TRADITIONS.find(t => t.id === cleanId) || null;
}

/**
 * Validates if an id is a recognized tradition.
 * @param {string} id
 * @returns {boolean}
 */
export function isValidTradition(id) {
  if (!id || typeof id !== 'string') return false;
  return ALLOWED_TRADITION_IDS.includes(id.trim().toLowerCase());
}
